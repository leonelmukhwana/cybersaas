-- ============================================================
-- UPDATE SUBSCRIPTION USAGE PEAKS
--
-- Branch creation/update affects branch peak.
-- Terminal creation/update affects terminal peak.
-- ============================================================

CREATE OR REPLACE FUNCTION update_subscription_usage_peaks()
RETURNS TRIGGER AS $$
DECLARE
    v_tenant_id UUID;
    v_branch_count INTEGER;
    v_terminal_count INTEGER;
BEGIN

    IF TG_TABLE_NAME = 'branches' THEN
        v_tenant_id := NEW.tenant_id;

    ELSIF TG_TABLE_NAME = 'terminals' THEN

        SELECT tenant_id
        INTO v_tenant_id
        FROM branches
        WHERE id = NEW.branch_id;

    END IF;


    IF v_tenant_id IS NULL THEN
        RETURN NEW;
    END IF;


    SELECT COUNT(*)
    INTO v_branch_count
    FROM branches
    WHERE tenant_id = v_tenant_id
      AND status = 'active';


    SELECT COUNT(*)
    INTO v_terminal_count
    FROM terminals t
    INNER JOIN branches b
        ON b.id = t.branch_id
    WHERE b.tenant_id = v_tenant_id
      AND t.status = 'active';


    UPDATE subscriptions
    SET
        peak_branches = GREATEST(
            peak_branches,
            v_branch_count
        ),

        peak_terminals = GREATEST(
            peak_terminals,
            v_terminal_count
        ),

        updated_at = NOW()

    WHERE tenant_id = v_tenant_id;


    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


