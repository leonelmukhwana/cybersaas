-- ============================================================
-- SESSIONS
--
-- IMPORTANT:
-- This table is RANGE PARTITIONED by started_at.
--
-- Because PostgreSQL requires the partition key to be included
-- in a primary/unique constraint, the primary key is:
--
--     (id, started_at)
--
-- The client still generates the UUID `id`.
--
-- No browsing history or URLs are stored.
-- ============================================================

CREATE TABLE sessions (
    id UUID NOT NULL,

    tenant_id UUID NOT NULL
        REFERENCES tenants(id)
        ON DELETE RESTRICT,

    branch_id UUID NOT NULL
        REFERENCES branches(id)
        ON DELETE RESTRICT,

    terminal_id UUID NOT NULL
        REFERENCES terminals(id)
        ON DELETE RESTRICT,

    customer_id UUID NOT NULL
        REFERENCES customers(id)
        ON DELETE RESTRICT,

    attendant_id UUID
        REFERENCES users(id)
        ON DELETE RESTRICT,

    session_type session_type NOT NULL,

    status session_status NOT NULL DEFAULT 'active',

    started_at TIMESTAMPTZ NOT NULL,

    ended_at TIMESTAMPTZ,

    prepaid_amount NUMERIC(12,2),

    allowed_minutes INTEGER,

    rate_per_minute NUMERIC(12,2),

    minimum_charge NUMERIC(12,2),

    final_amount NUMERIC(12,2),

    client_operation_id UUID NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (id, started_at),

    UNIQUE (client_operation_id, started_at),

    CHECK (
        ended_at IS NULL
        OR ended_at >= started_at
    ),

    CHECK (
        prepaid_amount IS NULL
        OR prepaid_amount >= 0
    ),

    CHECK (
        allowed_minutes IS NULL
        OR allowed_minutes >= 0
    ),

    CHECK (
        rate_per_minute IS NULL
        OR rate_per_minute >= 0
    ),

    CHECK (
        minimum_charge IS NULL
        OR minimum_charge >= 0
    ),

    CHECK (
        final_amount IS NULL
        OR final_amount >= 0
    )
)
PARTITION BY RANGE (started_at);


